"""Compare legacy/current archive JSON using public seed data in .build only.

Run with the bundled Python: python tools/check_compatibility.py
No user database is opened. All artifacts are retained for inspection; this tool
does not stage files, contact providers, or remove existing build directories.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import gzip
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
from uuid import uuid4


ROOT = Path(__file__).resolve().parents[1]
BASELINE_MODULES = (
    "database.py", "relationships.py", "tag_management.py",
    "published_tags.py", "provinces.py",
)
PUBLIC_RESOURCES = ("published-tags.json", "mainboard-catalog.json")

PROBE = '''"""Isolated compatibility worker; generated by check_compatibility.py."""
import json
from pathlib import Path
import socket
import sys
import time

def deny_network(*args, **kwargs):
    raise RuntimeError("network access is forbidden in compatibility probes")

socket.socket.connect = deny_network
socket.socket.connect_ex = deny_network
socket.create_connection = deny_network
socket.getaddrinfo = deny_network

root, module_path, db_path, output, timings_path = map(Path, sys.argv[1:])
if not db_path.resolve().is_relative_to((root / '.build').resolve()):
    raise ValueError("probe databases must be under .build")
sys.path.insert(0, str(root))
sys.path.insert(0, str(module_path))
import database as db
import tag_management
import published_tags

initialize = getattr(db, 'initialize', db.connect)
conn = initialize(db_path)
conn.close()
published_tags.apply(db_path)
conn = db.connect(db_path)
try:
    settings = db.get_settings(conn)
    start, end = settings['range_start'], settings['range_end']
    checks = {
        'meta': lambda: db.meta(conn),
        'date_latest': lambda: db.date_view(conn, end),
        'date_2025_10_14': lambda: db.date_view(conn, '2025-10-14'),
        'stock_000980': lambda: db.stock_view(conn, '000980', start, end),
        'stock_000678': lambda: db.stock_view(conn, '000678', start, end),
        'pair_000980_000678': lambda: db.stock_pair_comparison(conn, '000980', '000678', start, end, settings),
        'tag_catalog': lambda: tag_management.catalog(conn),
    }
    results, timings = {}, {}
    for name, query in checks.items():
        before = time.perf_counter()
        results[name] = query()
        timings[name] = round(time.perf_counter() - before, 6)
    output.write_text(json.dumps(results, ensure_ascii=False, sort_keys=True), encoding='utf-8')
    timings_path.write_text(json.dumps(timings, indent=2) + '\\n', encoding='utf-8')
finally:
    conn.close()
'''


def differences(before, after, path="$"):
    """Yield concrete differing JSON paths; keep array ordering significant."""
    if type(before) is not type(after):
        yield {"path": path, "reason": "type", "baseline": type(before).__name__, "current": type(after).__name__}
    elif isinstance(before, dict):
        for key in sorted(before.keys() | after.keys()):
            child = f"{path}.{key}"
            if key not in before or key not in after:
                yield {"path": child, "reason": "missing_key", "baseline": key in before, "current": key in after}
            else:
                yield from differences(before[key], after[key], child)
    elif isinstance(before, list):
        if len(before) != len(after):
            yield {"path": path, "reason": "length", "baseline": len(before), "current": len(after)}
        for index, (left, right) in enumerate(zip(before, after)):
            yield from differences(left, right, f"{path}[{index}]")
    elif before != after:
        yield {"path": path, "reason": "value", "baseline": before, "current": after}


def git_bytes(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True).stdout


def run(baseline_ref):
    commit = git_bytes("rev-parse", "--verify", "--end-of-options", baseline_ref + "^{commit}").decode("ascii").strip()
    build = ROOT / ".build"
    work = build / ("compatibility-" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ-") + uuid4().hex)
    work.mkdir(parents=True)
    baseline = work / "baseline"
    (baseline / "resources").mkdir(parents=True)
    for name in BASELINE_MODULES:
        (baseline / name).write_bytes(git_bytes("show", f"{commit}:{name}"))
    # A pre-sync local ref may already use the modular package. Materialize it
    # so its compatibility facades cannot silently import the current package.
    for name in git_bytes('ls-tree', '-r', '--name-only', commit, 'lianban').decode().splitlines():
        if name.endswith('.py'):
            target = baseline / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(git_bytes('show', f'{commit}:{name}'))
    resources = {}
    for name in PUBLIC_RESOURCES:
        source = ROOT / "resources" / name
        shutil.copyfile(source, baseline / "resources" / name)
        resources[name] = hashlib.sha256(source.read_bytes()).hexdigest()
    seed_path = ROOT / "resources" / "archive-seed.sqlite3.gz"
    seed = seed_path.read_bytes()
    resources[seed_path.name] = hashlib.sha256(seed).hexdigest()
    raw_seed = gzip.decompress(seed)
    for label in ("baseline", "current"):
        with (work / f"{label}.sqlite3").open("xb") as handle:
            handle.write(raw_seed)
    script = work / "probe.py"
    script.write_text(PROBE, encoding="utf-8")
    for label, modules in (("baseline", baseline), ("current", ROOT)):
        result = subprocess.run(
            [sys.executable, str(script), str(ROOT), str(modules),
             str(work / f"{label}.sqlite3"), str(work / f"{label}.json"), str(work / f"{label}-timings.json")],
            cwd=work, capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=180,
        )
        (work / f"{label}-stdout.txt").write_text(result.stdout, encoding="utf-8")
        (work / f"{label}-stderr.txt").write_text(result.stderr, encoding="utf-8")
        if result.returncode:
            raise RuntimeError(f"{label} probe failed; inspect {work / (label + '-stderr.txt')}")
    old = json.loads((work / "baseline.json").read_text(encoding="utf-8"))
    new = json.loads((work / "current.json").read_text(encoding="utf-8"))
    queries, examples, total = {}, [], 0
    for name in sorted(old.keys() | new.keys()):
        count = 0
        for difference in differences(old.get(name), new.get(name), "$." + name):
            count += 1
            if len(examples) < 100:
                examples.append(difference)
        queries[name] = {"equal": count == 0, "difference_count": count}
        total += count
    report = {
        "baseline_ref": baseline_ref, "baseline_commit": commit,
        "public_resource_sha256": resources, "artifact_directory": str(work),
        "queries": queries, "difference_count": total, "difference_examples": examples,
        "timings_seconds": {label: json.loads((work / f"{label}-timings.json").read_text(encoding="utf-8"))
                            for label in ("baseline", "current")},
    }
    (work / "report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for name, result in queries.items():
        print(f"{name}: {'MATCH' if result['equal'] else 'DIFFERENT'}")
    print(f"Artifacts: {work}")
    return 1 if total else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline-ref", default="b04ba1f", help="local Git revision for the legacy root modules")
    args = parser.parse_args()
    try:
        return run(args.baseline_ref)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        print(f"Compatibility check failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
